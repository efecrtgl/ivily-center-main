//! Settings: typed schema, validation, scoped storage and resolution.
//!
//! Precedence (lowest → highest): **default < user < workspace**. A setting declares which
//! scopes it accepts; e.g. the theme is user-only, while future editor settings will also accept
//! workspace scope. Values in the database that are unknown (written by a newer version) are
//! preserved but ignored; values that fail validation are ignored and reported.

pub mod schema;

use crate::core::now_ms;
use crate::error::{AppError, AppResult};
use rusqlite::{params, Connection, OptionalExtension};
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use std::collections::BTreeMap;

pub use schema::SETTINGS;

#[derive(Debug, Clone, Copy)]
pub enum SettingType {
    Bool,
    /// `(value, label)` pairs.
    Enum(&'static [(&'static str, &'static str)]),
    Integer {
        min: i64,
        max: i64,
    },
    String {
        max_len: usize,
    },
    /// A list of strings (e.g. glob patterns).
    StringList {
        max_items: usize,
        max_len: usize,
    },
}

#[derive(Debug, Clone, Copy)]
pub enum DefaultValue {
    Bool(bool),
    Int(i64),
    Str(&'static str),
    List(&'static [&'static str]),
}

impl DefaultValue {
    pub fn to_json(self) -> Value {
        match self {
            DefaultValue::Bool(b) => json!(b),
            DefaultValue::Int(i) => json!(i),
            DefaultValue::Str(s) => json!(s),
            DefaultValue::List(l) => json!(l),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ScopeSet {
    User,
    UserAndWorkspace,
}

#[derive(Debug, Clone, Copy)]
pub struct SettingDef {
    pub key: &'static str,
    pub title: &'static str,
    pub description: &'static str,
    pub category: &'static str,
    pub ty: SettingType,
    pub default: DefaultValue,
    pub scopes: ScopeSet,
}

/// Where a value is stored.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Scope {
    User,
    Workspace(String),
}

impl Scope {
    fn parts(&self) -> (&'static str, &str) {
        match self {
            Scope::User => ("user", ""),
            Scope::Workspace(id) => ("workspace", id.as_str()),
        }
    }

    /// Workspace ids are generated by Center (Phase 3); accept only a safe id format.
    pub fn workspace(id: &str) -> AppResult<Self> {
        let ok = (1..=64).contains(&id.len()) && id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_');
        if !ok {
            return Err(AppError::validation("invalid_workspace_id", "workspace id is malformed"));
        }
        Ok(Scope::Workspace(id.to_string()))
    }
}

pub fn find(key: &str) -> Option<&'static SettingDef> {
    SETTINGS.iter().find(|d| d.key == key)
}

/// Validate `value` against `def`, returning the normalized value.
pub fn validate(def: &SettingDef, value: &Value) -> AppResult<Value> {
    let bad = |msg: String| AppError::validation("invalid_setting_value", format!("{}: {msg}", def.key));
    match def.ty {
        SettingType::Bool => value.as_bool().map(Value::Bool).ok_or_else(|| bad("expected true or false".into())),
        SettingType::Enum(options) => {
            let s = value.as_str().ok_or_else(|| bad("expected a string".into()))?;
            if options.iter().any(|(v, _)| *v == s) {
                Ok(json!(s))
            } else {
                Err(bad(format!("'{s}' is not one of the allowed values")))
            }
        }
        SettingType::Integer { min, max } => {
            let n = value.as_i64().ok_or_else(|| bad("expected an integer".into()))?;
            if (min..=max).contains(&n) {
                Ok(json!(n))
            } else {
                Err(bad(format!("must be between {min} and {max}")))
            }
        }
        SettingType::String { max_len } => {
            let s = value.as_str().ok_or_else(|| bad("expected a string".into()))?;
            if s.chars().count() <= max_len && !s.chars().any(|c| c.is_control()) {
                Ok(json!(s))
            } else {
                Err(bad(format!("must be at most {max_len} characters without control characters")))
            }
        }
        SettingType::StringList { max_items, max_len } => {
            let arr = value.as_array().ok_or_else(|| bad("expected a list of strings".into()))?;
            if arr.len() > max_items {
                return Err(bad(format!("at most {max_items} entries")));
            }
            let mut out = Vec::with_capacity(arr.len());
            for v in arr {
                let s = v.as_str().ok_or_else(|| bad("every entry must be a string".into()))?.trim();
                if s.is_empty() {
                    continue;
                }
                if s.chars().count() > max_len || s.chars().any(|c| c.is_control()) {
                    return Err(bad(format!(
                        "entries must be at most {max_len} characters without control characters"
                    )));
                }
                out.push(Value::from(s));
            }
            Ok(Value::Array(out))
        }
    }
}

fn check_scope(def: &SettingDef, scope: &Scope) -> AppResult<()> {
    if matches!(scope, Scope::Workspace(_)) && def.scopes == ScopeSet::User {
        return Err(AppError::validation(
            "setting_not_workspace_scoped",
            format!("{} can only be set per user", def.key),
        ));
    }
    Ok(())
}

fn known(key: &str) -> AppResult<&'static SettingDef> {
    find(key).ok_or_else(|| AppError::validation("unknown_setting", format!("unknown setting: {key}")))
}

/// Raw stored values for a scope (unvalidated).
fn load_scope(conn: &Connection, scope: &Scope) -> AppResult<BTreeMap<String, String>> {
    let (s, id) = scope.parts();
    let mut stmt = conn.prepare_cached("SELECT key, value FROM settings WHERE scope = ?1 AND scope_id = ?2")?;
    let rows = stmt.query_map(params![s, id], |r| Ok((r.get::<_, String>(0)?, r.get::<_, String>(1)?)))?;
    Ok(rows.collect::<Result<_, _>>()?)
}

#[derive(Debug, Clone, Copy, Serialize, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum Source {
    Default,
    User,
    Workspace,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct Resolved {
    /// Effective value.
    pub value: Value,
    /// Layer the effective value comes from.
    pub source: Source,
    /// The user layer's own (valid) value, if set — shown when a workspace overrides it.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub user_value: Option<Value>,
    /// The workspace layer's own (valid) value, if set.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub workspace_value: Option<Value>,
}

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct InvalidStored {
    pub key: String,
    pub scope: &'static str,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ResolvedSettings {
    pub values: BTreeMap<&'static str, Resolved>,
    /// Stored values ignored because they failed validation (e.g. edited by hand or from an
    /// older/newer version). They are not deleted.
    pub invalid: Vec<InvalidStored>,
}

/// Where the workspace layer of settings comes from.
pub enum WorkspaceLayer<'a> {
    None,
    /// Folder workspaces: rows in `settings` with scope `workspace` and this id.
    Db(&'a str),
    /// Workspace files: the file's `settings` object.
    Values(&'a serde_json::Map<String, Value>),
}

/// Raw workspace-layer values (unvalidated JSON text per key).
pub fn workspace_layer_raw(conn: &Connection, layer: &WorkspaceLayer<'_>) -> AppResult<BTreeMap<String, String>> {
    Ok(match layer {
        WorkspaceLayer::None => BTreeMap::new(),
        WorkspaceLayer::Db(id) => load_scope(conn, &Scope::Workspace(id.to_string()))?,
        WorkspaceLayer::Values(map) => map.iter().map(|(k, v)| (k.clone(), v.to_string())).collect(),
    })
}

/// Resolve every registered setting: default < user < workspace layer.
pub fn resolve(conn: &Connection, layer: &WorkspaceLayer<'_>) -> AppResult<ResolvedSettings> {
    let user = load_scope(conn, &Scope::User)?;
    let ws = workspace_layer_raw(conn, layer)?;
    let mut values = BTreeMap::new();
    let mut invalid = Vec::new();
    for def in SETTINGS {
        let mut resolved =
            Resolved { value: def.default.to_json(), source: Source::Default, user_value: None, workspace_value: None };
        let layers: [(&BTreeMap<String, String>, Source, &'static str, bool); 2] = [
            (&user, Source::User, "user", true),
            (&ws, Source::Workspace, "workspace", def.scopes == ScopeSet::UserAndWorkspace),
        ];
        for (map, source, scope_name, allowed) in layers {
            let Some(raw) = map.get(def.key) else { continue };
            let parsed = serde_json::from_str::<Value>(raw).ok().and_then(|v| validate(def, &v).ok());
            match parsed {
                Some(v) if allowed => {
                    if source == Source::User {
                        resolved.user_value = Some(v.clone());
                    } else {
                        resolved.workspace_value = Some(v.clone());
                    }
                    resolved.value = v;
                    resolved.source = source;
                }
                _ => invalid.push(InvalidStored { key: def.key.to_string(), scope: scope_name }),
            }
        }
        values.insert(def.key, resolved);
    }
    Ok(ResolvedSettings { values, invalid })
}

/// Validate a value for the workspace scope without storing it (workspace files).
pub fn validate_workspace_value(key: &str, value: &Value) -> AppResult<Value> {
    let def = known(key)?;
    check_scope(def, &Scope::Workspace(String::new()))?;
    validate(def, value)
}

/// Check that a key exists and accepts workspace scope.
pub fn check_workspace_key(key: &str) -> AppResult<()> {
    check_scope(known(key)?, &Scope::Workspace(String::new()))
}

/// Validate and store a value. Returns the normalized value.
pub fn set(conn: &Connection, scope: &Scope, key: &str, value: &Value) -> AppResult<Value> {
    let def = known(key)?;
    check_scope(def, scope)?;
    let v = validate(def, value)?;
    let (s, id) = scope.parts();
    conn.execute(
        "INSERT INTO settings (scope, scope_id, key, value, updated_at) VALUES (?1, ?2, ?3, ?4, ?5)
         ON CONFLICT (scope, scope_id, key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at",
        params![s, id, key, v.to_string(), now_ms()],
    )?;
    Ok(v)
}

/// Remove a stored value so the next lower scope (or the default) applies.
pub fn reset(conn: &Connection, scope: &Scope, key: &str) -> AppResult<()> {
    known(key)?;
    let (s, id) = scope.parts();
    conn.execute("DELETE FROM settings WHERE scope = ?1 AND scope_id = ?2 AND key = ?3", params![s, id, key])?;
    Ok(())
}

/// Read one resolved user-scope value (or the default) — for backend consumers.
pub fn get_user(conn: &Connection, key: &str) -> AppResult<Value> {
    let def = known(key)?;
    let raw: Option<String> = conn
        .query_row("SELECT value FROM settings WHERE scope = 'user' AND scope_id = '' AND key = ?1", [key], |r| {
            r.get(0)
        })
        .optional()?;
    Ok(raw
        .and_then(|r| serde_json::from_str::<Value>(&r).ok())
        .and_then(|v| validate(def, &v).ok())
        .unwrap_or_else(|| def.default.to_json()))
}

/// Apply key renames: move `old` to `new` in every scope where `new` is not already set.
pub fn migrate_keys(conn: &Connection, renamed: &[(&str, &str)]) -> AppResult<usize> {
    let mut moved = 0;
    for (old, new) in renamed {
        moved += conn.execute("UPDATE OR IGNORE settings SET key = ?2 WHERE key = ?1", params![old, new])?;
        conn.execute("DELETE FROM settings WHERE key = ?1", params![old])?;
    }
    Ok(moved)
}

/// Schema as sent to the UI (settings editor, search, validation hints).
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SettingSchemaDto {
    pub key: &'static str,
    pub title: &'static str,
    pub description: &'static str,
    pub category: &'static str,
    #[serde(rename = "type")]
    pub ty: &'static str,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub options: Option<Vec<OptionDto>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub min: Option<i64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub max: Option<i64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub max_length: Option<usize>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub max_items: Option<usize>,
    pub default: Value,
    pub scopes: Vec<&'static str>,
}

#[derive(Debug, Serialize)]
pub struct OptionDto {
    pub value: &'static str,
    pub label: &'static str,
}

pub fn schema_dto() -> Vec<SettingSchemaDto> {
    SETTINGS
        .iter()
        .map(|d| {
            let mut max_items = None;
            let (ty, options, min, max, max_length) = match d.ty {
                SettingType::Bool => ("boolean", None, None, None, None),
                SettingType::Enum(o) => (
                    "enum",
                    Some(o.iter().map(|(value, label)| OptionDto { value, label }).collect()),
                    None,
                    None,
                    None,
                ),
                SettingType::Integer { min, max } => ("integer", None, Some(min), Some(max), None),
                SettingType::String { max_len } => ("string", None, None, None, Some(max_len)),
                SettingType::StringList { max_items: n, max_len } => {
                    max_items = Some(n);
                    ("stringList", None, None, None, Some(max_len))
                }
            };
            SettingSchemaDto {
                key: d.key,
                title: d.title,
                description: d.description,
                category: d.category,
                ty,
                options,
                min,
                max,
                max_length,
                max_items,
                default: d.default.to_json(),
                scopes: match d.scopes {
                    ScopeSet::User => vec!["user"],
                    ScopeSet::UserAndWorkspace => vec!["user", "workspace"],
                },
            }
        })
        .collect()
}

/// Wire form of a scope in IPC requests. `workspace` always means the workspace open in the
/// calling window, so the UI cannot address another workspace's settings.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum ScopeArg {
    User,
    Workspace,
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::db::{migrate, MIGRATIONS};

    fn conn() -> Connection {
        let mut c = Connection::open_in_memory().unwrap();
        migrate(&mut c, MIGRATIONS, None).unwrap();
        c
    }

    #[test]
    fn registry_is_consistent() {
        let mut keys = std::collections::HashSet::new();
        for d in SETTINGS {
            assert!(keys.insert(d.key), "duplicate key {}", d.key);
            assert!(d.key.contains('.'), "{} must be namespaced", d.key);
            validate(d, &d.default.to_json()).unwrap_or_else(|e| panic!("default of {} invalid: {e}", d.key));
        }
    }

    #[test]
    fn validation_rejects_wrong_types_and_ranges() {
        let theme = find("appearance.theme").unwrap();
        assert!(validate(theme, &json!("pixel-dark")).is_ok());
        assert!(validate(theme, &json!("nope")).is_err());
        assert!(validate(theme, &json!(3)).is_err());
        let size = find("appearance.uiFontSize").unwrap();
        assert!(validate(size, &json!(13)).is_ok());
        assert!(validate(size, &json!(9)).is_err());
        assert!(validate(size, &json!(13.5)).is_err());
        let b = find("window.restoreBounds").unwrap();
        assert!(validate(b, &json!("true")).is_err());
    }

    #[test]
    fn set_resolve_and_reset_user_value() {
        let c = conn();
        assert_eq!(resolve(&c, &WorkspaceLayer::None).unwrap().values["appearance.theme"].source, Source::Default);
        set(&c, &Scope::User, "appearance.theme", &json!("glass")).unwrap();
        let r = resolve(&c, &WorkspaceLayer::None).unwrap();
        assert_eq!(
            (&r.values["appearance.theme"].value, r.values["appearance.theme"].source),
            (&json!("glass"), Source::User)
        );
        assert_eq!(get_user(&c, "appearance.theme").unwrap(), json!("glass"));
        reset(&c, &Scope::User, "appearance.theme").unwrap();
        assert_eq!(get_user(&c, "appearance.theme").unwrap(), json!("modern-dark"));
    }

    #[test]
    fn unknown_keys_and_user_only_settings_are_rejected() {
        let c = conn();
        assert!(set(&c, &Scope::User, "nope.key", &json!(1)).is_err());
        let ws = Scope::workspace("ws_1").unwrap();
        assert!(set(&c, &ws, "appearance.uiFontSize", &json!(14)).is_err());
        assert!(Scope::workspace("../evil").is_err());
        assert!(Scope::workspace("").is_err());
    }

    #[test]
    fn workspace_scope_overrides_user_when_allowed_and_is_ignored_otherwise() {
        let c = conn();
        // Simulate a stored workspace value for a user-only setting (e.g. hand-edited database).
        c.execute("INSERT INTO settings VALUES ('workspace', 'ws1', 'appearance.uiFontSize', '18', 0)", []).unwrap();
        set(&c, &Scope::User, "appearance.uiFontSize", &json!(15)).unwrap();
        let r = resolve(&c, &WorkspaceLayer::Db("ws1")).unwrap();
        assert_eq!(r.values["appearance.uiFontSize"].value, json!(15));
        assert_eq!(r.invalid, vec![InvalidStored { key: "appearance.uiFontSize".into(), scope: "workspace" }]);

        // Workspace-capable setting: the workspace value wins over the user value.
        set(&c, &Scope::User, "appearance.theme", &json!("glass")).unwrap();
        set(&c, &Scope::workspace("ws1").unwrap(), "appearance.theme", &json!("pixel-dark")).unwrap();
        let r = resolve(&c, &WorkspaceLayer::Db("ws1")).unwrap();
        let theme = &r.values["appearance.theme"];
        assert_eq!((&theme.value, theme.source), (&json!("pixel-dark"), Source::Workspace));
        assert_eq!(theme.user_value, Some(json!("glass")), "user value is still reported");
        assert_eq!(theme.workspace_value, Some(json!("pixel-dark")));
        // Another workspace and no workspace see the user value: no leakage between workspaces.
        assert_eq!(resolve(&c, &WorkspaceLayer::Db("ws2")).unwrap().values["appearance.theme"].value, json!("glass"));
        assert_eq!(resolve(&c, &WorkspaceLayer::None).unwrap().values["appearance.theme"].value, json!("glass"));

        // The file layer behaves the same way; invalid file values are reported, not applied.
        let mut file = serde_json::Map::new();
        file.insert("appearance.theme".into(), json!("retro-terminal"));
        file.insert("appearance.reduceMotion".into(), json!("on"));
        let r = resolve(&c, &WorkspaceLayer::Values(&file)).unwrap();
        assert_eq!(r.values["appearance.theme"].value, json!("retro-terminal"));
        assert_eq!(r.values["appearance.reduceMotion"].source, Source::Default);
        assert!(r.invalid.iter().any(|i| i.key == "appearance.reduceMotion"));
        assert!(validate_workspace_value("appearance.theme", &json!("glass")).is_ok());
        assert!(validate_workspace_value("appearance.uiFontSize", &json!(14)).is_err());
    }

    #[test]
    fn invalid_stored_values_fall_back_and_are_reported_not_deleted() {
        let c = conn();
        c.execute("INSERT INTO settings VALUES ('user', '', 'appearance.theme', '\"removed-theme\"', 0)", []).unwrap();
        c.execute("INSERT INTO settings VALUES ('user', '', 'future.setting', 'true', 0)", []).unwrap();
        let r = resolve(&c, &WorkspaceLayer::None).unwrap();
        assert_eq!(r.values["appearance.theme"].value, json!("modern-dark"));
        assert_eq!(r.invalid.len(), 1);
        let n: i64 = c.query_row("SELECT count(*) FROM settings", [], |r| r.get(0)).unwrap();
        assert_eq!(n, 2, "stored values must be preserved");
    }

    #[test]
    fn key_migration_moves_values_without_overwriting() {
        let c = conn();
        c.execute("INSERT INTO settings VALUES ('user', '', 'old.a', '1', 0)", []).unwrap();
        c.execute("INSERT INTO settings VALUES ('user', '', 'old.b', '2', 0)", []).unwrap();
        c.execute("INSERT INTO settings VALUES ('user', '', 'new.b', '3', 0)", []).unwrap();
        migrate_keys(&c, &[("old.a", "new.a"), ("old.b", "new.b")]).unwrap();
        let get = |k: &str| -> Option<String> {
            c.query_row("SELECT value FROM settings WHERE key = ?1", [k], |r| r.get(0)).optional().unwrap()
        };
        assert_eq!(get("new.a").as_deref(), Some("1"));
        assert_eq!(get("new.b").as_deref(), Some("3"), "existing new value wins");
        assert_eq!(get("old.a"), None);
        assert_eq!(get("old.b"), None);
    }

    #[test]
    fn scope_arg_parsing() {
        assert_eq!(serde_json::from_value::<ScopeArg>(json!("user")).unwrap(), ScopeArg::User);
        assert_eq!(serde_json::from_value::<ScopeArg>(json!("workspace")).unwrap(), ScopeArg::Workspace);
        assert!(serde_json::from_value::<ScopeArg>(json!({ "kind": "workspace", "workspaceId": "x" })).is_err());
    }
}
